M = 5003
v = {1:27, 2:123, 3:567, 4:2643, 5:2441}
# f(n) = a f(n-1) + b f(n-2)
# 567 = a*123 + b*27 ; 2643 = a*567 + b*123
A = [[v[2], v[1], v[3]], [v[3], v[2], v[4]]]
det = (A[0][0]*A[1][1] - A[0][1]*A[1][0]) % M
print("det", det)
inv = pow(det, -1, M)
a = ((A[0][2]*A[1][1] - A[0][1]*A[1][2]) * inv) % M
b = ((A[0][0]*A[1][2] - A[0][2]*A[1][0]) * inv) % M
print("a,b =", a, b)
print("check f(5):", (a*v[4] + b*v[3]) % M, "observed", v[5])
