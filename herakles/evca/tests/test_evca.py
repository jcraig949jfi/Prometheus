def test_c1a_hand_computed_neighbourhood_index():
    """One state, indices worked out by hand from the pinned bit order."""
    # N = 7, a single 1 at position 3. For cell 3 the neighbourhood is the
    # whole ring, 0001000, so idx = 1 << 3 = 8.
    s = np.array([[0, 0, 0, 1, 0, 0, 0]], dtype=np.uint8)
    idx = evca.neighbourhood_index(s)
    assert idx[0, 3] == 0b0001000 == 8
    # For cell 0 the neighbourhood is cells 4,5,6,0,1,2,3 = 0,0,0,0,0,0,1,
    # so the single 1 sits in the LEAST significant position.
    assert idx[0, 0] == 0b0000001 == 1
    # For cell 6 the neighbourhood is 3,4,5,6,0,1,2 = 1,0,0,0,0,0,0.
    assert idx[0, 6] == 0b1000000 == 64


def test_c1a_uniform_states_have_the_extreme_indices():
    n = 9
    zeros = np.zeros((1, n), dtype=np.uint8)
    ones = np.ones((1, n), dtype=np.uint8)
    assert (evca.neighbourhood_index(zeros) == 0).all()
    assert (evca.neighbourhood_index(ones) == evca.TABLE_BITS - 1).all()


@pytest.mark.parametrize("name", G.NAMES)
def test_c1a_step_matches_the_independent_oracle(name):
    h = G.rule_hex(name)
    table = evca.decode_table(h)
    bits = oracle_decode(h)
    assert list(table) == bits, "decoders disagree before dynamics"
    rng = np.random.default_rng(20260908)
    for n_cells in (7, 9, 15, 21):
        cells = rng.integers(0, 2, size=n_cells).astype(np.uint8)
        got = evca.evolve(cells[None, :], table, 5)[0].tolist()
        want = oracle_evolve(cells.tolist(), bits, 5)
        assert got == want, (name, n_cells)


def test_c1a_msb_convention_is_forced_not_assumed():
    """Re-earn the bit-order convention instead of trusting the record.

    `maj` and `GKL` are derivable from their definitions. Under the pinned
    order both reproduce the published hex in all 32 digits; under the
    reversed order neither does. The convention is therefore identified by
    the data, not chosen.
    """
    assert evca.encode_table(evca.majority_rule_table()) == G.rule_hex("maj")
    assert evca.encode_table(evca.gkl_rule_table()) == G.rule_hex("GKL")
    # the mirrored convention must NOT also fit, or the test proves nothing
    flipped = evca.reflect_table(evca.gkl_rule_table())
    assert evca.encode_table(flipped) != G.rule_hex("GKL")


def test_c1a_encode_decode_round_trip():
    for name in G.NAMES:
        h = G.rule_hex(name)
        assert evca.encode_table(evca.decode_table(h)) == h


