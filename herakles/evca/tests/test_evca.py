@pytest.mark.parametrize("name", G.NAMES)
def test_c1d_reflection_equivariance(name):
    table = evca.decode_table(G.rule_hex(name))
    ics = evca.make_ics(16, 21, seed=7)
    steps = 12

    base = evca.evolve(ics, table, steps, record=True)
    mirrored = evca.evolve(evca.reflect_states(ics),
                           evca.reflect_table(table), steps, record=True)

    # The naive check would compare raw bytes and fail. Prove that first, so
    # the normalisation is doing real work rather than hiding a mismatch.
    assert evca.trajectory_digest(base) != evca.trajectory_digest(mirrored)

    undone = evca.normalise_trajectory(mirrored, reflected=True)
    assert evca.trajectory_digest(undone) == evca.trajectory_digest(base)


@pytest.mark.parametrize("name", G.NAMES)
def test_c1d_complement_equivariance(name):
    table = evca.decode_table(G.rule_hex(name))
    ics = evca.make_ics(16, 21, seed=11)
    steps = 12

    base = evca.evolve(ics, table, steps, record=True)
    flipped = evca.evolve(evca.complement_states(ics),
                          evca.complement_table(table), steps, record=True)
    assert evca.trajectory_digest(base) != evca.trajectory_digest(flipped)

    undone = evca.normalise_trajectory(flipped, complemented=True)
    assert evca.trajectory_digest(undone) == evca.trajectory_digest(base)


@pytest.mark.parametrize("name", G.NAMES)
def test_c1d_joint_reflection_and_complement(name):
    table = evca.decode_table(G.rule_hex(name))
    ics = evca.make_ics(16, 21, seed=13)
    steps = 12
    base = evca.evolve(ics, table, steps, record=True)

    both_table = evca.complement_table(evca.reflect_table(table))
    both_ics = evca.complement_states(evca.reflect_states(ics))
    both = evca.evolve(both_ics, both_table, steps, record=True)

    undone = evca.normalise_trajectory(both, reflected=True, complemented=True)
    assert evca.trajectory_digest(undone) == evca.trajectory_digest(base)


@pytest.mark.parametrize("name", G.NAMES)
def test_c1d_correctness_mask_is_invariant_under_both_symmetries(name):
    """The scientific invariant: WHICH ICs are misclassified must not move.

    Complement also flips the majority target, which is why the mask is the
    right object to compare and the accuracy alone is not.
    """
    table = evca.decode_table(G.rule_hex(name))
    ics = evca.make_ics(64, 21, seed=17)
    steps = 42

    base = evca.classify(table, ics, steps, witness_limit=64)
    refl = evca.classify(evca.reflect_table(table),
                         evca.reflect_states(ics), steps, witness_limit=64)
    comp = evca.classify(evca.complement_table(table),
                         evca.complement_states(ics), steps, witness_limit=64)

    assert refl["correct_mask_digest"] == base["correct_mask_digest"], name
    assert comp["correct_mask_digest"] == base["correct_mask_digest"], name
    assert refl["witness"] == base["witness"]
    assert comp["witness"] == base["witness"]


