def test_import_has_no_side_effects():
    """No file writes, no stdout, no global-RNG consumption, on import."""
    code = (
        "import numpy as np, io, sys\n"
        "np.random.seed(1234)\n"
        "before = np.random.random()\n"
        "np.random.seed(1234)\n"
        "buf = io.StringIO(); old = sys.stdout; sys.stdout = buf\n"
        "import herakles.evca as m\n"
        "sys.stdout = old\n"
        "after = np.random.random()\n"
        "assert before == after, 'global RNG was consumed at import'\n"
        "assert buf.getvalue() == '', 'import wrote to stdout'\n"
        "print('OK')\n"
    )
    out = subprocess.run([sys.executable, "-c", code], cwd=REPO,
                         capture_output=True, text=True)
    assert out.returncode == 0, out.stderr
    assert out.stdout.strip().endswith("OK")


