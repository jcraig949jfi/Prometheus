# ---------------------------------------------------------------------------
# The independent oracle. Written from the convention, not from core.py.
# ---------------------------------------------------------------------------

def oracle_index(cells, i):
    """Neighbourhood index of cell i, leftmost neighbour as MSB, ring."""
    n = len(cells)
    idx = 0
    for j, off in enumerate(range(-3, 4)):
        bit = cells[(i + off) % n]
        idx += bit << (6 - j)
    return idx


def oracle_step(cells, table_bits):
    n = len(cells)
    return [table_bits[oracle_index(cells, i)] for i in range(n)]


def oracle_evolve(cells, table_bits, steps):
    cur = list(cells)
    for _ in range(steps):
        cur = oracle_step(cur, table_bits)
    return cur


def oracle_decode(hex_string):
    bits = bin(int(hex_string, 16))[2:].zfill(128)
    return [int(b) for b in bits]


