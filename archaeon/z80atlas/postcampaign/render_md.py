"""Render Z80ATLAS_POSTCAMPAIGN_ADJUDICATION_<date>.md from the adjudication JSON + replay JSONs. Every number in the .md is
read from those files here; the only hand-written text is the fixed wording of the directive's required statements.

    python -m archaeon.z80atlas.postcampaign.render_md --date 2026-09-23
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def pct(a, b):
    return "%.1f%%" % (100.0 * a / b) if b else "n/a"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--date", required=True); a = ap.parse_args(argv)
    adj = load(HERE / ("Z80ATLAS_POSTCAMPAIGN_ADJUDICATION_%s.json" % a.date)); rc = load(HERE / ("AUDIT_RECEIPT_%s.json" % a.date))
    rp = {k: load(HERE / "replays" / ("REPLAY_%s.json" % k)) for k in ("flagged", "named", "witness_sample", "denovo_candidates")}
    A, B, C, D, E, Fw = (adj[k] for k in ("A_reclassification", "B_rescoring", "C_transplant", "D_topology", "E_recombination", "F_seeded_witness_confound"))
    L = []; w = L.append
    w("# Z80 x Atlas -- post-campaign adjudication (%s)" % a.date); w("")
    w("Archaeon, M2. Directive: `roles/Archaeon/prompts/2026-09-23_z80atlas_postcampaign/00_OPERATOR_DIRECTIVE.md`. "
      "Generated by `archaeon/z80atlas/postcampaign/render_md.py` from `Z80ATLAS_POSTCAMPAIGN_ADJUDICATION_%s.json`, "
      "`AUDIT_RECEIPT_%s.json` and `replays/REPLAY_*.json`; no number below is typed by hand." % (a.date, a.date)); w("")
    w("The historical campaign records were read, never written (`historical_records_modified: false`). The original packet "
      "`archaeon/z80atlas/campaign/CAMPAIGN_PACKET.md` stays as it is: it is the historical record, and this document does not replace it. Input fingerprints (sha256):"); w("")
    for k, v in adj["inputs_sha256"].items(): w("- `%s` `%s`" % (k, v))
    w(""); w("Reconstruction check: the campaign's own scorer (`scheduler.Campaign.family_table`, unchanged since `%s`), re-run over the preserved "
             "RUNS.jsonl, reproduces the historical PACKET top-30 exactly: **%s**. Every corrected number below comes from that same scorer, "
             "with only the invalid flag removed." % (adj["campaign_code_commit"], adj["reconstruction_verified"])); w("")

    # ---- A
    w("## A. Reclassification of the 26 flagged runs"); w("")
    w("**Verified de-novo spontaneous replication in the completed campaign = %d** (of %d DONE runs)." % (A["verified_de_novo_spontaneous_replication"], A["denominator_runs_done"])); w("")
    w("All %d runs the legacy label flagged are reclassified **`transplanted_lineage_replication`**. Every one is a late-stage transplant "
      "verification run whose founders were all transplanted tapes. Every transplant source was itself an `init=seeded_replicator` run "
      "(`sources_all_seeded: %s`), so the material was inserted twice over: evolved in a seeded world, then carried in by the experimenter. "
      "Unresolved: %s." % (A["reclassified_transplanted_lineage_replication"], rc["sources_all_seeded"], A["unresolved"] or "none")); w("")
    w("Verification kinds as the packet labelled them: %s; counting every RUNS.jsonl row: %s. The difference is `%s`, which was scheduled twice "
      "with an identical spec: family 2ace470e5c47's task was COND_multi, and the environment-swap table maps an unknown task to COND_multi, "
      "so that **environment swap was vacuous** (same world as transplant:same)." % (rc["verification_kind_counts_as_packet_labelled"], rc["verification_kind_counts_all_rows"], ", ".join(rc["vacuous_environment_swaps"]))); w("")
    w("| run_id | family | kind(s) | task | topology | reproduction | tapes | source run (init) |"); w("|---|---|---|---|---|---|---|---|")
    for x in A["runs"]:
        s = x["source"] or {}
        w("| `%s` | %s | %s | %s | %s | %s | %d | `%s` (%s) |" % (x["run_id"], x["family"], " + ".join(k.replace("transplant:", "") for k in x["verification_kinds"]) + (" (vacuous)" if x["environment_swap_was_vacuous"] else ""),
                                                          x["task"], x["topology"], x["reproduction"], x["transplanted_tapes"], s.get("run_id"), s.get("init")))
    fl = rp.get("flagged")
    if fl:
        ok = [r for r in fl["results"] if r["admitted"]]
        w(""); w("Instrumented replay corroboration (`replays/REPLAY_flagged.json`): %d/%d preserved (spec, seed) pairs were replayed with the repaired engine and "
                 "**admitted** (every legacy signal byte-identical to the preserved RECEIPT). In every admitted replay: legacy label reproduced = %d/%d, "
                 "repaired `spontaneous_replication` = true in %d, random founders = %d in total, clean endogenous births = %d in total, "
                 "inserted-lineage replication = true in %d." % (
                     len(ok), fl["n"], sum(r["provenance"] is not None and r["historical_spontaneous_label"] for r in ok), len(ok),
                     sum(r["repaired_spontaneous_replication"] for r in ok), sum(r["provenance"]["founders"]["random"] for r in ok),
                     sum(r["provenance"]["births_endo_clean"] for r in ok), sum(r["inserted_lineage_replication"] for r in ok)))
    w("")

    # ---- B
    w("## B. Family scores, original vs corrected"); w("")
    w("`spontaneous_replication` carried weight 5. It has been removed from the %d affected runs and nothing else has changed. A family's score is the maximum over its runs, so a family "
      "keeps whatever its best remaining run earns." % len(A["runs"])); w("")
    w("| family | original score (rank) | corrected score (rank) | flag removed | original best run | corrected best run | flags now |"); w("|---|---|---|---|---|---|---|")
    for fam, r in B["named"].items():
        w("| **%s** | %d (%d) | %d (%d) | %s | `%s` | `%s` | %s |" % (fam, r["original_score"], r["original_rank"], r["corrected_score"], r["corrected_rank"], ", ".join(r["flags_removed"]) or "-",
                                                               r["original_best_run"], r["corrected_best_run"], ", ".join(r["corrected_flags"])))
    w("")
    ties = sorted({r["corrected_score"] for r in B["corrected_top30"]})
    w("The three named families drop from 17 to %s. Their score-17 runs were all transplant runs; with the flag removed those runs score 12, and each family's "
      "maximum now comes from its original exploration/control run (14, which adds `compression` where the transplant run had none). The corrected "
      "top 30 contains only the score(s) %s. **The corrected ordering is a tie; ranks within it are dict-order artifacts and carry no information.**"
      % ("/".join(str(B["named"][f]["corrected_score"]) for f in B["named"]), ties)); w("")
    w("All families touched by the correction:"); w("")
    w("| family | original -> corrected | rank | flags removed |"); w("|---|---|---|---|")
    for fam, r in sorted(B["families_touched"].items(), key=lambda x: x[1]["original_rank"]):
        w("| %s | %d -> %d | %d -> %d | %s |" % (fam, r["original_score"], r["corrected_score"], r["original_rank"], r["corrected_rank"], ", ".join(r["flags_removed"]) or "none"))
    w(""); w("Corrected flag total `spontaneous_replication` = %d." % B["flag_totals_corrected"]["spontaneous_replication"]); w("")

    # ---- C
    w("## C. What the transplant runs genuinely establish"); w("")
    th = C["thresholds_frozen_grammar"]
    w("Mechanical readings use the frozen grammar's own thresholds: persisted = alive and final population >= %.2f N; reproduced = >= %d endogenous births; "
      "competence retained = final best task score >= %.3f. Source = the run the tapes came from." % (th["persist_pop_frac"], th["reproduce_births"], th["competence"])); w("")
    w("| family | transplant | reproduction / topology | task (source task) | persisted (pop) | reproduced endo (births, fidelity) | competence final / source best |"); w("|---|---|---|---|---|---|---|")
    for fam in sorted(C["families"]):
        for k, v in sorted(C["families"][fam].items()):
            w("| %s | %s%s | %s / %s | %s (%s) | %s (%.3f) | %s (%d, %s) | %s / %s |" % (fam, k.replace("transplant:", ""), " VACUOUS" if v["vacuous"] else "", v["reproduction"], v["topology"],
                                                                                 v["task"], v["source_task"], "yes" if v["persisted"] else "NO", v["final_pop_frac"],
                                                                                 "yes" if v["reproduced_endogenously"] else ("n/a (EXTERNAL)" if v["reproduction"] == "EXTERNAL" else "NO"),
                                                                                 v["births_endo"], v["fidelity_late"], v["task_competence_final"], v["source_best_ever"]))
    allr = [v for f in C["families"].values() for v in f.values()]
    endo = [v for v in allr if v["reproduction"] != "EXTERNAL"]
    w(""); w("Summary over %d transplant runs (%d endogenous): persisted %d/%d; endogenous reproduction %d/%d; competence retained (>= %.3f) %d/%d; "
             "physics swap to EXTERNAL persisted %d/%d. The seeded-derived lineages **persist and self-replicate at high fidelity when moved**: same world, "
             "world swap (niches -> well_mixed) and task swap alike. **Task competence mostly does not travel**: the sources reached a best score of 1.0, and "
             "most transplanted populations finish at 0.0 on the same task. This is a transplanted-lineage persistence result, which is a real and "
             "positive finding. It is not a de-novo result, and it is not a competence-transport result." % (
                 len(allr), len(endo), sum(v["persisted"] for v in allr), len(allr), sum(v["reproduced_endogenously"] for v in endo), len(endo),
                 th["competence"], sum(v["competence_retained"] for v in allr), len(allr),
                 sum(v["persisted"] for v in allr if v["reproduction"] == "EXTERNAL"), sum(1 for v in allr if v["reproduction"] == "EXTERNAL"))); w("")
    w("Corrected interpretation of **5b237a475b69**: a seeded-replicator family (task ADD2, niches). Its tapes, taken from `a0132ad72787_s1_cont`, persisted and "
      "self-replicated after transplant into the same world, a well-mixed world, and a COND_multi world. It kept none of its ADD2 competence after transplant. "
      "Its exploration run still carries moat_crossed / moat_advantage, but in a seeded-hybrid world those are subject to the witness confound (section F). "
      "Corrected family score %d, tied with the rest of the top 30." % B["named"]["5b237a475b69"]["corrected_score"]); w("")

    # ---- D
    w("## D. Niches-regime association (not a topology effect)"); w("")
    def tab(t):
        w("| level | runs | moat_crossed rate | moat_advantage runs | moat_advantage rate |"); w("|---|---|---|---|---|")
        for k, v in t.items(): w("| %s | %d | %.3f | %d | %.4f |" % (k, v["runs"], v["moat_crossed_rate"], v["moat_advantage"], v["moat_advantage_rate"]))
        w("")
    w("All DONE runs by topology:"); w(""); tab(D["all_runs_by_topology"])
    w("Exploration runs only (the scheduler's non-adaptive draws):"); w(""); tab(D["exploration_runs_by_topology"])
    w("Allocation by topology and kind: %s" % json.dumps(D["allocation_by_topology_and_kind"])); w("")
    w("Levels niches exploration actually drew: %s" % json.dumps(D["niches_exploration_levels"])); w("")
    w("Why niches is confounded: %s. Inside niches, the 'bare' subset (no migration, no reservoir, no niche-moving env dynamics) holds %d runs, all of them adaptively "
      "allocated; exploration produced none of them. Adaptive promotion then sent %d promotion runs to niches, against about 200 for each other topology. **The "
      "campaign shows a niches-regime association. It cannot separate topology from migration, reservoir, niche-local environment dynamics or allocation.** "
      "Phase 4 separates them by design." % (D["sampler_note"], D["niches_split_by_coupled_features"].get([k for k in D["niches_split_by_coupled_features"] if k.startswith("niches_bare")][0], {}).get("runs", 0),
                                             D["allocation_by_topology_and_kind"]["niches"].get("promotion", 0))); w("")

    # ---- E
    w("## E. Recombination: confounded by construction"); w("")
    p = E["treatment_control_pairs"]
    w("Grammar constraint: %s. `%s`." % (E["grammar_constraint"], E["matched_control_rule"])); w("")
    w("Exact pairing, with each control recomputed from its treatment's preserved SPEC: %d recombination treatments; %d of their reproduction controls ran; controls that "
      "keep recombination = **%d**; controls that are ENDOGENOUS_COPY = %d; treatments that also lost `explicit_fitness` in the control = %d (controls keeping it = %d). "
      "Every moat_advantage on a recombination row therefore compares EXTERNAL+recombination(+selection) against endogenous copying without recombination or "
      "selection. Three factors change at once. **No causal recombination effect can be read from these rows.**" % (
          p["recombination_treatments"], p["control_ran"], p["control_has_recombination"], p.get("control_reproduction_ENDOGENOUS_COPY", 0),
          p["treatment_had_explicit_fitness"], p["control_keeps_explicit_fitness"])); w("")
    w("The only comparison that holds reproduction physics fixed is within EXTERNAL runs:"); w("")
    w("All EXTERNAL runs (adaptively allocated):"); w(""); tab(E["within_EXTERNAL_all"])
    w("EXTERNAL exploration runs only:"); w(""); tab(E["within_EXTERNAL_exploration_only"])
    w("The apparent elevation among all runs does not survive restriction to exploration draws. There it is the difference shown above, a few points, with "
      "moat_advantage still measured against an endogenous control. The '3-5x recombination pressure' reading is an allocation artifact plus the construction confound."); w("")

    # ---- F
    w("## F. A second instrumentation confound of the same class: task crossing in seeded worlds"); w("")
    w("This is not in the directive's list, but it is the same defect class, so it is reported. With `init=seeded_replicator` and `init_hybrid` (the grammar default), the seeded tape is "
      "`tasks.task_then_replicate`: the **hand-written task witness** followed by a replicator. A crossing in such a world can be the inserted witness "
      "scoring, not an evolved solution. `moat_crossed` (weight 2) and `moat_advantage` (weight 6) never asked where the crossing organism came from."); w("")
    w("| init / task | runs | crossed | crossed at epoch 0 | crossed by epoch 5 |"); w("|---|---|---|---|---|")
    for k, v in Fw["moat_crossed_by_init"].items():
        w("| %s | %d | %d (%s) | %d (%s of crossed) | %d |" % (k, v["runs"], v.get("crossed", 0), pct(v.get("crossed", 0), v["runs"]), v.get("crossed_at_epoch0", 0), pct(v.get("crossed_at_epoch0", 0), v.get("crossed", 0)), v.get("crossed_by_epoch5", 0)))
    w(""); w("moat_advantage runs by init and first-crossing epoch: %s. Families scoring 14 (the corrected top tier), by best-run init: %s (of %d)." % (
        json.dumps(Fw["moat_advantage_runs_by_init_and_first_crossing_epoch"]), json.dumps(Fw["families_scoring_14_by_best_run_init"]), Fw["families_scoring_14"])); w("")
    for name in ("named", "witness_sample"):
        r = rp.get(name)
        if not r: continue
        ok = [x for x in r["results"] if x["admitted"]]
        w("Instrumented replay `%s` (%d/%d admitted). First-crossing ancestry per replay:" % (name, len(ok), r["n"])); w("")
        w("| run | init | reproduction | task | first crossing epoch | crosser inserted? | crosser = unmodified founder tape? | origins |"); w("|---|---|---|---|---|---|---|---|")
        for x in ok:
            for t, c in (x["provenance"].get("first_crossing") or {}).items():
                w("| `%s` | %s | %s | %s | %d | %s | %s | %s |" % (x["run_id"], x["init"], x["reproduction"], t, c["epoch"], c["inserted_ancestry"], c["is_unmodified_founder_tape"], ",".join(c["origins"])))
            if not x["provenance"].get("first_crossing"):
                w("| `%s` | %s | %s | %s | - | no crossing | - | - |" % (x["run_id"], x["init"], x["reproduction"], x["task"]))
        w("")
        seeded = [c for x in ok if x["init"] == "seeded_replicator" for c in (x["provenance"].get("first_crossing") or {}).values()]
        rnd = [c for x in ok if x["init"] == "random" for c in (x["provenance"].get("first_crossing") or {}).values()]
        w("Seeded-world first crossings by inserted-ancestry organisms: %d/%d (of which the unmodified hand-written seeded tape itself: %d); the rest are random-ancestry organisms, so the confound is PARTIAL. Random-world crossings by inserted-ancestry organisms: %d/%d." % (
            sum(c["inserted_ancestry"] for c in seeded), len(seeded), sum(c["is_unmodified_founder_tape"] and c["inserted_ancestry"] for c in seeded), sum(c["inserted_ancestry"] for c in rnd), len(rnd))); w("")
    w("Status: the confound is measured from the records, and per-run attribution comes from the admitted replays above. The historical scores are **not** "
      "re-corrected for it here. The directive's correction is limited to the spontaneous flag, and a moat re-score needs its own ruling (see the recommendation)."); w("")

    # ---- G
    w("## G. The campaign's de-novo denominator"); w("")
    dn = rp.get("denovo_candidates"); G = adj["G_denovo_denominator"]
    w("From the preserved records: %d random-init endogenous runs received no inserted material (%s). %d went extinct (median extinction epoch %s, max %s). "
      "Founders die at max_age %d, so a world with no replicator is dead by roughly that epoch. The most endogenous births in any extinct run was %d. The legacy label fired on %d of these runs. "
      "Runs that did **not** go extinct: **%d**." % (G["random_init_endogenous_runs_without_inserted_material"], json.dumps(G["by_reproduction"]), G["extinct"], G["median_extinct_epoch"],
                                                     G["max_extinct_epoch"], 60, G["max_births_endo_among_extinct"], G["legacy_label_fired_on_any"], len(G["not_extinct"]))); w("")
    for s in G["not_extinct"]:
        w("- `%s` (`%s`): %s; final population %.3f, endogenous births %d, late fidelity %s, epochs %d (vm_steps %d: budget exhausted), final lineages %d, task best %s." % (
            s["run_id"], s["run_dir"], ", ".join("%s=%s" % (k.split(".")[-1], v) for k, v in s["factors"].items()), s["final_pop_frac"], s["births_endo"], s["fidelity_late"],
            s["epochs"], s["vm_steps"], s["lineages_final"], s["best_ever"]))
    w(""); w("It fails the frozen fidelity threshold, so under the frozen definition it is **not** spontaneous replication. It is still the campaign's only record of a "
             "**self-sustaining, random-origin endogenous reproducer**, and the full replay below explains how it works."); w("")
    if dn:
        for x in dn["results"]:
            pv = x["provenance"]
            w("Instrumented replay of `%s`: admitted=%s; founders %s; clean endogenous births %d (at fidelity >= 0.9: %s); clean fidelity %.3f; final clean population %d; "
              "repaired predicate %s; first clean replication %s; first clean high-fidelity replication %s." % (
                  x["run_id"], x["admitted"], json.dumps(pv["founders"]), pv["births_endo_clean"], pv.get("births_endo_clean_hifi", "n/a"), pv["fid_clean"], pv["final_pop_clean"],
                  x["repaired_spontaneous_replication"], json.dumps({k: pv["first_clean_replication"][k] for k in ("epoch", "generation", "fid", "lineage")}) if pv["first_clean_replication"] else None,
                  json.dumps({k: pv["first_clean_hifi_replication"][k] for k in ("epoch", "generation", "fid", "lineage", "parent_tape")}) if pv.get("first_clean_hifi_replication") else None))
        w("")
    obs = HERE / "replays" / "84616cf8257b_s1_cont"
    if (obs / "SNAPSHOTS.json.gz").exists():
        import gzip
        from collections import Counter
        sys.path.insert(0, str(HERE.parents[2]))
        from archaeon.z80atlas import engine as E, vm
        sn = json.load(gzip.open(obs / "SNAPSHOTS.json.gz", "rt", encoding="utf-8"))
        prov = json.loads((obs / "PROVENANCE.json").read_text(encoding="utf-8"))["summary"]; fr = prov["first_clean_hifi_replication"]; L0 = fr["lineage"]; tape = bytes.fromhex(fr["parent_tape"])
        w("Full observatory files for that replay are in `archaeon/z80atlas/postcampaign/replays/84616cf8257b_s1_cont/` (SPEC, RECEIPT, TELEMETRY, SNAPSHOTS, PROVENANCE). "
          "Lineage `%d` (a single random founder) by snapshot:" % L0); w("")
        w("| epoch | snapshot | population | lineages | organisms of lineage %d | exact founder tape present |" % L0); w("|---|---|---|---|---|---|")
        seen = set()
        for s in sn["snapshots"]:
            if s["epoch"] in seen: continue
            seen.add(s["epoch"]); c = Counter(o["lineage"] for o in s["organisms"])
            w("| %d | %s | %d | %d | %d | %s |" % (s["epoch"], s["reason"], len(s["organisms"]), len(c), c.get(L0, 0), any(o["tape"] == fr["parent_tape"] for o in s["organisms"])))
        fp = sn["final_population"]; tc = Counter(o["tape"] for o in fp)
        w(""); w("Final population: %d organisms, lineages %s, max generation %d, %d distinct tapes; most common final tape `%s` (x%d)." % (
            len(fp), dict(Counter(o["lineage"] for o in fp)), max(o["generation"] for o in fp), len(tc), tc.most_common(1)[0][0], tc.most_common(1)[0][1])); w("")
        rows = []
        for x in range(256):
            r = vm.execute(tape, bytes(len(tape)), (x,), 256, True); m = sum(r["nbr_mask"]) / len(tape)
            rows.append((x, m >= 0.9, E.fidelity(r["nbr_window"], tape)))
        births = [x for x, b, f in rows if b]; exact = [x for x, b, f in rows if b and f >= 0.999]
        w("Mechanism (executed here with the frozen VM, empty neighbour, one input byte, all 256 inputs). The founder tape `%s` is a COPY loop whose "
          "destination register is loaded from the task input (`IN C` ... `COPY` ... `JR -7`). Inputs that yield a birth (>= copy_min_frac of the window written): "
          "%d of 256. Inputs that yield an exact self-copy (fidelity 1.0): %s. **The only random-origin reproducer in the campaign is an input-gated self-copier.** "
          "It copies itself exactly only when the environment supplies one particular byte, and otherwise writes a shifted copy. The lineage then diversified "
          "into zero-padded, shifted variants (the modal final tape is a NOP sled into the loop)." % (fr["parent_tape"], len(births), exact)); w("")
    (HERE / ("Z80ATLAS_POSTCAMPAIGN_ADJUDICATION_%s.md" % a.date)).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("wrote", HERE / ("Z80ATLAS_POSTCAMPAIGN_ADJUDICATION_%s.md" % a.date)); return 0


if __name__ == "__main__":
    sys.exit(main())
