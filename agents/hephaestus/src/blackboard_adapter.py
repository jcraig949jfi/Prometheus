def adapt_engines():
    """Write the adapted ops to Apollo's source directory."""
    APOLLO_SRC.mkdir(parents=True, exist_ok=True)

    code = ADAPTED_OPS_CODE.replace("{timestamp}", datetime.now().isoformat())

    OUTPUT_PATH.write_text(code, encoding="utf-8")
    log.info("Wrote adapted ops to %s", OUTPUT_PATH)

    # Verify it parses
    import ast
    try:
        ast.parse(code)
        log.info("Syntax OK")
    except SyntaxError as e:
        log.error("Syntax error in adapted ops: %s", e)
        return False

    # Write status
    status = {
        "last_adapted": datetime.now().isoformat(),
        "output_path": str(OUTPUT_PATH),
        "ops_count": code.count("@blackboard_op"),
        "tiers": ["R1", "R2", "R2", "R3", "R4", "R5"],
    }
    STATUS_PATH.write_text(json.dumps(status, indent=2), encoding="utf-8")
    return True


def test_adapted():
    """Quick smoke test of the adapted ops."""
    # We can't import Apollo's blackboard directly (different machine path)
    # but we can verify the code is valid Python
    import ast
    code = OUTPUT_PATH.read_text(encoding="utf-8")
    ast.parse(code)
    log.info("Adapted ops parse OK (%d lines, %d ops)",
             len(code.splitlines()), code.count("@blackboard_op"))


def daemon_loop(interval_sec=1800):
    """Run adapter periodically. Check for new forge output, re-adapt if needed."""
    log.info("Adapter daemon started (interval=%ds)", interval_sec)
    while True:
        try:
            # Check if composer.py changed since last adapt
            composer_path = Path(__file__).resolve().parent / "composer.py"
            composer_mtime = composer_path.stat().st_mtime if composer_path.exists() else 0

            last_adapted = 0
            if STATUS_PATH.exists():
                try:
                    status = json.loads(STATUS_PATH.read_text(encoding="utf-8"))
                    from datetime import datetime as dt
                    last_adapted = dt.fromisoformat(status["last_adapted"]).timestamp()
                except Exception:
                    pass

            if composer_mtime > last_adapted:
                log.info("Composer changed since last adapt — re-adapting")
                adapt_engines()
            else:
                log.info("No changes detected, sleeping %ds", interval_sec)
        except Exception as e:
            log.warning("Adapter error: %s", e)

        time.sleep(interval_sec)


def main():
    parser = argparse.ArgumentParser(description="Blackboard Adapter")
    parser.add_argument("--adapt", action="store_true", help="Adapt engines now")
    parser.add_argument("--test", action="store_true", help="Test adapted ops")
    parser.add_argument("--daemon", action="store_true", help="Run adapter loop")
    parser.add_argument("--interval", type=int, default=1800, help="Daemon interval (sec)")
    args = parser.parse_args()

    if args.adapt:
        adapt_engines()
    if args.test:
        test_adapted()
    if args.daemon:
        adapt_engines()  # Initial adapt
        daemon_loop(interval_sec=args.interval)
    if not (args.adapt or args.test or args.daemon):
        adapt_engines()


if __name__ == "__main__":
    main()
