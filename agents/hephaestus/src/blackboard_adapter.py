# ── R1: Parse rules from natural language ─────────────────────────────

_COND = re.compile(r"[Ii]f\\s+(.+?),?\\s+[Tt]hen\\s+(.+?)(?:\\.|,|$)")
_NEG = re.compile(r"\\b(not|no|never|neither|cannot)\\b", re.I)
_COMP = re.compile(
    r"(\\w+(?:\\s+\\w+)*)\\s+(?:is\\s+)?(?:greater|larger|more|bigger|"
    r"higher|taller|heavier|older)\\s+than\\s+(\\w+(?:\\s+\\w+)*)", re.I)
_NUM = re.compile(r"-?\\d+(?:\\.\\d+)?")


@blackboard_op(
    reads=["problem_text"],
    writes=["rules", "facts"],
    precondition=lambda s: bool(s.problem_text),
)
def parse_rules(state: BlackboardState) -> BlackboardState:
    """R1: Extract if-then rules and initial facts from text."""
    text = state.problem_text
    rules = defaultdict(list)
    facts = set()

    # Extract conditionals: "if X then Y"
    for ante, conseq in _COND.findall(text):
        rules[ante.strip().lower()].append(conseq.strip().lower())

    # Extract causal: "X causes Y", "X leads to Y"
    for m in re.finditer(r"(\\w[\\w\\s]*?)\\s+(?:causes|leads\\s+to|results\\s+in)\\s+(\\w[\\w\\s]*?)(?:\\.|,|$)", text, re.I):
        rules[m.group(1).strip().lower()].append(m.group(2).strip().lower())

    # Extract negated facts
    for m in _NEG.finditer(text):
        start = max(0, m.start() - 30)
        context = text[start:m.end() + 30].lower()
        facts.add(f"neg:{context.strip()}")

    # Extract asserted facts (sentences without "if")
    for sentence in re.split(r"[.!?]", text):
        s = sentence.strip().lower()
        if s and "if " not in s and len(s) > 5:
            facts.add(s)

    state.rules = dict(rules)
    state.facts = facts
    return state


# ── R2: Forward chaining — THE KEY R2 OPERATION ──────────────────────

@blackboard_op(
    reads=["rules", "facts"],
    writes=["derived_facts"],
    precondition=lambda s: bool(getattr(s, "rules", None)),
)
def forward_chain(state: BlackboardState) -> BlackboardState:
    """R2: Fixpoint inference closure over rules and facts.

    This is the constraint-tracking operation Apollo's substrate lacks.
    It performs genuine multi-step deduction: repeatedly applies rules
    until no new facts can be derived.

    Kill test: zero derived_facts → downstream scorer accuracy collapses.
    """
    rules = getattr(state, "rules", {})
    facts = set(getattr(state, "facts", set()))
    derived = set(facts)
    queue = deque(facts)

    iterations = 0
    max_iterations = 100

    while queue and iterations < max_iterations:
        current = queue.popleft()
        iterations += 1

        for premise, conclusions in rules.items():
            if premise in current or current in premise:
                for conclusion in conclusions:
                    if conclusion not in derived:
                        derived.add(conclusion)
                        queue.append(conclusion)

    state.derived_facts = derived
    return state


# ── R2: Ordering resolve (transitive closure) ────────────────────────

@blackboard_op(
    reads=["relations"],
    writes=["transitive_closure", "ordered"],
    precondition=lambda s: bool(s.relations),
)
def ordering_resolve(state: BlackboardState) -> BlackboardState:
    """R2: Compute transitive closure over ordering relations.

    Given (A > B), (B > C), derives A > C and produces a total order.
    """
    gt = defaultdict(set)
    for a, b in state.relations:
        gt[a.lower()].add(b.lower())

    # Transitive closure via BFS
    closure = defaultdict(set)
    all_entities = set(gt.keys())
    for v in gt.values():
        all_entities |= v

    for entity in all_entities:
        visited = set()
        q = deque([entity])
        while q:
            curr = q.popleft()
            for lesser in gt.get(curr, set()):
                if lesser not in visited:
                    visited.add(lesser)
                    q.append(lesser)
        closure[entity] = visited

    # Build total order by rank (number of entities each is greater than)
    rank = {e: len(closure.get(e, set())) for e in all_entities}
    ordered = sorted(all_entities, key=lambda e: -rank.get(e, 0))

    state.transitive_closure = dict(closure)
    state.ordered = ordered
    return state


# ── R3: Sequence detection ────────────────────────────────────────────

@blackboard_op(
    reads=["numbers"],
    writes=["sequence_type", "sequence_next"],
    precondition=lambda s: len(s.numbers) >= 3,
)
def sequence_detect(state: BlackboardState) -> BlackboardState:
    """R3: Infer the pattern type from a number sequence and predict next."""
    seq = state.numbers

    # Arithmetic: constant difference
    diffs = [seq[i+1] - seq[i] for i in range(len(seq)-1)]
    if len(set(round(d, 6) for d in diffs)) == 1 and diffs[0] != 0:
        state.sequence_type = "arithmetic"
        state.sequence_next = seq[-1] + diffs[0]
        return state

    # Geometric: constant ratio
    if all(s != 0 for s in seq[:-1]):
        ratios = [seq[i+1] / seq[i] for i in range(len(seq)-1)]
        if len(set(round(r, 6) for r in ratios)) == 1 and ratios[0] != 1:
            state.sequence_type = "geometric"
            state.sequence_next = seq[-1] * ratios[0]
            return state

    # Fibonacci-like
    if all(abs(seq[i] - (seq[i-1] + seq[i-2])) < 0.01 for i in range(2, len(seq))):
        state.sequence_type = "fibonacci"
        state.sequence_next = seq[-1] + seq[-2]
        return state

    # Quadratic (second differences constant)
    if len(diffs) >= 2:
        dd = [diffs[i+1] - diffs[i] for i in range(len(diffs)-1)]
        if len(set(round(d, 6) for d in dd)) == 1 and dd[0] != 0:
            state.sequence_type = "quadratic"
            state.sequence_next = seq[-1] + diffs[-1] + dd[0]
            return state

    state.sequence_type = "unknown"
    state.sequence_next = 0.0
    return state


# ── R4: State machine simulation ─────────────────────────────────────

_STATE_TRANS = re.compile(
    r"[Ss]tate\\s+(\\w+)\\s*\\+?\\s*input\\s*'?(\\w)'?\\s*->\\s*[Ss]tate\\s+(\\w+)")
_INPUT_SEQ = re.compile(r"input\\s+sequence[:\\s]+([01]+)", re.I)
_START_STATE = re.compile(r"[Ss]tarting\\s+(?:in\\s+)?[Ss]tate\\s+(\\w+)")


@blackboard_op(
    reads=["problem_text"],
    writes=["state_current"],
    precondition=lambda s: "State" in s.problem_text or "state" in s.problem_text,
)
def state_simulate(state: BlackboardState) -> BlackboardState:
    """R4: Simulate a state machine step by step.

    Parses transition table, initial state, and input sequence from text.
    Simulates through each input symbol and writes the final state.
    """
    text = state.problem_text
    transitions = _STATE_TRANS.findall(text)

    if not transitions:
        return state

    table = {}
    for s, inp, ns in transitions:
        table.setdefault(s, {})[inp] = ns

    start = _START_STATE.search(text)
    seq = _INPUT_SEQ.search(text)

    if not start or not seq:
        return state

    current = start.group(1)
    for symbol in seq.group(1):
        if current in table and symbol in table[current]:
            current = table[current][symbol]

    state.state_current = current
    return state


# ── R5: Causal trace ─────────────────────────────────────────────────

_CAUSES = re.compile(
    r"(\\w[\\w\\s]*?)\\s+(?:causes|leads\\s+to|results\\s+in)\\s+(\\w[\\w\\s]*?)(?:\\.|,|$)", re.I)
_CORRELATION = re.compile(r"(?:correlat|associat|linked|related)", re.I)


@blackboard_op(
    reads=["problem_text"],
    writes=["causal_edges", "causal_query_type", "causal_answer"],
    precondition=lambda s: bool(re.search(r"cause|correlat|leads to", s.problem_text, re.I)),
)
def causal_trace(state: BlackboardState) -> BlackboardState:
    """R5: Build causal DAG and reason about interventions.

    Distinguishes correlation from causation. Detects common-effect
    confounders. Returns structured causal conclusion.
    """
    text = state.problem_text

    edges = [(m.group(1).strip(), m.group(2).strip()) for m in _CAUSES.finditer(text)]
    state.causal_edges = edges

    has_correlation = bool(_CORRELATION.search(text))

    if has_correlation:
        state.causal_query_type = "correlation"
        state.causal_answer = "Cannot determine"
        return state

    # Build DAG
    dag = defaultdict(set)
    for cause, effect in edges:
        dag[cause.lower()].add(effect.lower())

    # Check for common-effect pattern
    effects = defaultdict(list)
    for cause, effs in dag.items():
        for e in effs:
            effects[e].append(cause)

    for effect, causes in effects.items():
        if len(causes) > 1:
            state.causal_query_type = "common_effect"
            state.causal_answer = "Cannot determine"
            return state

    state.causal_query_type = "direct"
    state.causal_answer = "Yes" if edges else "Unknown"
    return state


# ── Terminal scorers (translate derived state → candidate scores) ─────

@blackboard_op(
    reads=["derived_facts", "candidates"],
    writes=["candidate_scores", "selected_answer"],
    precondition=lambda s: bool(getattr(s, "derived_facts", None)),
)
def score_by_derivability(state: BlackboardState) -> BlackboardState:
    """Score candidates by whether they appear in derived facts."""
    derived = getattr(state, "derived_facts", set())
    scores = []
    for c in state.candidates:
        if c.lower() in derived or any(c.lower() in f for f in derived):
            scores.append(1.0)
        else:
            scores.append(0.0)
    state.candidate_scores = scores
    if scores:
        best_idx = scores.index(max(scores))
        state.selected_answer = state.candidates[best_idx]
    return state


@blackboard_op(
    reads=["ordered", "candidates", "problem_text"],
    writes=["candidate_scores", "selected_answer"],
    precondition=lambda s: bool(s.ordered),
)
def score_by_ordering(state: BlackboardState) -> BlackboardState:
    """Score candidates by their position in the transitive ordering."""
    prompt = state.problem_text.lower()
    want_max = any(w in prompt for w in ["tallest", "greatest", "largest",
                                          "heaviest", "oldest", "most", "fastest"])
    target = state.ordered[0] if want_max else state.ordered[-1]

    scores = []
    for c in state.candidates:
        if c.lower() == target or target in c.lower() or c.lower() in target:
            scores.append(1.0)
        else:
            scores.append(0.0)
    state.candidate_scores = scores
    if scores:
        best_idx = scores.index(max(scores))
        state.selected_answer = state.candidates[best_idx]
    return state


@blackboard_op(
    reads=["sequence_next", "candidates"],
    writes=["candidate_scores", "selected_answer"],
    precondition=lambda s: getattr(s, "sequence_next", 0) != 0,
)
def score_by_sequence(state: BlackboardState) -> BlackboardState:
    """Score candidates by match to predicted sequence next value."""
    predicted = getattr(state, "sequence_next", 0)
    scores = []
    for c in state.candidates:
        try:
            if abs(float(c) - predicted) < 0.01:
                scores.append(1.0)
            else:
                scores.append(0.0)
        except ValueError:
            scores.append(0.0)
    state.candidate_scores = scores
    if scores:
        best_idx = scores.index(max(scores))
        state.selected_answer = state.candidates[best_idx]
    return state


