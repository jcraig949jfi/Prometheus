"""TEST-4 (Beta-01): T51 -- NATURAL-RECURRENCE DONOR STAGE (TH-019). Frozen spec: beta01/windows/T04_T51_SPEC.md.

Lineage-generated supply (W8 CG-1 LIN, seeds 0-7, 144 families each; regenerated byte-for-byte = W8 F1) replaces
constructed recurrence. The estimand is a POOLED dose relationship (W8 F4, W1 WP-2): across seeds x panel
schemas S, does reuse of the inherited schema's selected library rise with the natural recurrence dose X_S (W8
genuine COND_8)? G1 is one point in the pool, never the hypothesis.

Pipeline (escrow 30k everywhere inside the engine: a declared change from A19/A23's 250k, required by W8 F5/F6):
  foundry   a18_c1.qualify_family (Q2 + T4 v1 + PRISTINE/L1 pilots at 30k) for all 8 x 144 families
  roles     A19 NAT rule (seeded per seed): OBSERVE 4 (0 < p_PRISTINE <= .75), VALIDATE 4 (p <= .75),
            TRANSFER 32 (p <= .75; W1 WP-3 breadth)
  donors    a18_c1._donor_job, unchanged, for arms G1, PA, PB, PC, PD (held = arm, composition ON), P, G1_NC
  transfer  v2b D endpoint: walk.first_qualified at cap 1,000,000, tribunal T4 v1a; libraries SEL_<arm>,
            START_<held>, PRISTINE; 2 cells per TRANSFER family
Stages: plan | foundry [w] | roles | donors [w] | transfer [w] | report.
"""
