b02.BLOCKS = {"A": list(range(72, 96)), "B": list(range(96, 120))}
LIBS = ["L_g11", "L_I0", "L_P"]
MACH = ("g11", "O10")
PC_MIN_FAMILIES, PC_MIN_PAIRS = 5, 3
MIN_PAIRS = 18
